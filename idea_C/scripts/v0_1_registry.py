def _match_numbered_object(label: str, kind: str, key: str) -> bool:
    """Match ``--figure 1`` to Figure 1 but not Figure 10; ``2`` hits 2(a)/2 power."""
    name = label.lower()
    if kind not in name:
        return False
    compact = key.strip().lower().replace(" ", "")
    match = re.search(rf"{kind}\s+([0-9]+(?:\([a-d]\))?[a-d]?)", name, re.I)
    if match is None:
        return compact in name.replace(" ", "")
    token = match.group(1).lower()
    token_num = re.match(r"(\d+)", token)
    key_num = re.match(r"(\d+)(.*)", compact)
    if token_num is None or key_num is None:
        return compact in token
    if token_num.group(1) != key_num.group(1):
        return False
    rest = key_num.group(2).replace("(", "").replace(")", "")
    if not rest:
        return True
    return rest in token.replace("(", "").replace(")", "")


def objects_for(
    paper: str | None = None,
    figure: str | None = None,
    table: str | None = None,
    benchmark: str | None = None,
    object_id: str | None = None,
) -> list[dict[str, Any]]:
    """Filter checklist objects. All filters AND together."""
    out: list[dict[str, Any]] = []
    fig_key = None if figure is None else str(figure).strip().lower()
    tab_key = None if table is None else str(table).strip().lower()
    for obj in OBJECTS:
        if paper and obj["paper"] != paper:
            continue
        if object_id and obj["id"] != object_id:
            continue
        if benchmark and obj["benchmark"] != benchmark:
            continue
        if fig_key and not _match_numbered_object(str(obj["object"]), "figure", fig_key):
            continue
        if tab_key and not _match_numbered_object(str(obj["object"]), "table", tab_key):
            continue
        out.append(obj)
    return out


def counts_by_paper() -> dict[str, int]:
    counts = {p: 0 for p in PAPERS}
    for obj in OBJECTS:
        counts[obj["paper"]] += 1
    return counts


def flatten_extractable_numbers() -> list[dict[str, Any]]:
    """Paper numbers that may be compared to a local CSV.

    Figure-only objects emit a single FIGURE_ONLY row so the gap table
    cannot grow fake precision.
    """
    rows: list[dict[str, Any]] = []
    for obj in OBJECTS:
        kind = obj.get("numeric_kind")
        if kind == "FIGURE_ONLY" or kind == "NOT_LOCATED":
            rows.append(
                {
                    "object_id": obj["id"],
                    "paper": obj["paper"],
                    "object": obj["object"],
                    "method": None,
                    "metric": ",".join(obj.get("metrics") or []),
                    "paper_value": "FIGURE_ONLY" if kind == "FIGURE_ONLY" else "NOT_LOCATED_IN_PDF",
                    "kind": kind,
                    "deterministic": False,
                    "alpha": None,
                }
            )
            continue
        if obj.get("paper_numbers"):
            for method, value in obj["paper_numbers"].items():
                rows.append(
                    {
                        "object_id": obj["id"],
                        "paper": obj["paper"],
                        "object": obj["object"],
                        "method": method,
                        "metric": (obj.get("metrics") or ["value"])[0],
                        "paper_value": value,
                        "kind": "table",
                        "deterministic": bool(obj.get("deterministic")),
                        "alpha": None,
                    }
                )
            continue
        if obj.get("paper_table_rows"):
            role_map = {
                "LORD": {"Baseline": "e-LORD", "SCORE": "SCORE-LORD", "SCORE+": "SCORE+-LORD"},
                "SAFFRON": {"Baseline": "e-SAFFRON", "SCORE": "SCORE-SAFFRON", "SCORE+": "SCORE+-SAFFRON"},
            }
            for rec in obj["paper_table_rows"]:
                fam = rec["family"]
                for role in ("Baseline", "SCORE", "SCORE+"):
                    method = role_map[fam][role]
                    for metric_key, metric_name in (
                        (f"{role}_FDR", "FDR(T)"),
                        (f"{role}_Power", "Power(T)"),
                    ):
                        rows.append(
                            {
                                "object_id": obj["id"],
                                "paper": obj["paper"],
                                "object": obj["object"],
                                "method": method,
                                "metric": metric_name,
                                "paper_value": rec[metric_key],
                                "kind": "table",
                                "deterministic": False,
                                "alpha": rec["alpha"],
                                "pi1": rec["pi1"],
                                "family": fam,
                            }
                        )
                for role, metric_name in (("SCORE", "power_ratio"), ("SCORE+", "power_ratio")):
                    method = role_map[fam][role]
                    rows.append(
                        {
                            "object_id": obj["id"],
                            "paper": obj["paper"],
                            "object": obj["object"],
                            "method": method,
                            "metric": metric_name,
                            "paper_value": rec[f"{role}_ratio"],
                            "kind": "table",
                            "deterministic": False,
                            "alpha": rec["alpha"],
                            "pi1": rec["pi1"],
                            "family": fam,
                        }
                    )
    return rows
